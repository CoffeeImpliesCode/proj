//! The build half of PROJ's runtime route: four modules and two generated
//! files.
//!
//! An SDK that ships the runtime route calls `createModule` in place of
//! `translate.createModule()` and imports what comes back as its `c` module.
//! Nothing here links the native library. That is the point: in this
//! configuration the symbols arrive through the platform loader at run time, and
//! linking the archive as well would make the linker demand them before `load`
//! ever runs.
//!
//!   rt        runtime/loader.zig, the reusable core. Pure Zig; imported by the
//!             facade in both configurations, because `LoadSource` and
//!             `LoadError` are this SDK's public types and must be the same
//!             types whichever configuration is built.
//!   library   runtime/library.zig, this SDK's descriptor: the namespaced
//!             synchronization binding, and the load-time checks that prove the
//!             record layouts and the object-returning entry points behave.
//!   dispatch  generated by runtime/generate.zig from the real translation
//!             output: the table, the 292 wrappers, `load`, and the re-exported
//!             translated namespace. It imports `rt`, `library` and the
//!             generator's patched translation as `c_native`.
//!   native    the generator's second file: the same translation with the
//!             `const __root = @This();` prologue Aro writes replaced by an
//!             import of the dispatch as `c_routed`, so a declaration nested
//!             inside a translated type names the routed wrapper rather than the
//!             raw extern. It imports the dispatch and nothing else.
//!   sync.c    compiled into the dispatch with `-DRT_SYNC_PREFIX=proj_rt`, so
//!             its symbols cannot collide with another SDK's.
//!
//! ## The shape this file follows
//!
//! This is the two-output variant, taken from the template this package was
//! ported from: `generate.zig` is always given `--native-output`, the file that
//! argument names becomes the dispatch's `c_native` import, and `c_routed` is
//! added back to that module. Nothing in this file writes the dispatch itself,
//! and nothing caches it across configurations: the generator is a host program
//! that reads this target's own translation output, so a different header
//! configuration produces a different translation step output, which produces a
//! different dispatch.
//!
//! ## The one thing a caller must not do
//!
//! Do not link the compiled C archive into a module that imports this dispatch.
//! The facade's `c` import is the dispatch, and nothing else in the graph should
//! reference the library, or the linker resolves the symbols statically and the
//! runtime route silently becomes a linked one. For PROJ there is a second
//! reason, which is specific to this library: `libproj` is the one archive in
//! this workspace that has a *large* export list of its own, so linking it would
//! satisfy `dlsym` for names this table never asked about, and the refusal a
//! mismatched provider is supposed to get would quietly stop happening.

const std = @import("std");

/// The translation step `createModule` takes.
///
/// This is `*std.Build.Step.TranslateC`, which is what `b.addTranslateC`
/// returns (`std/Build.zig:1115`), spelled once here so the signature below
/// names a thing rather than a path into std. `build.zig` calls
/// `graph.createModule(b, translate, target, optimize)` with the very step it
/// has already made for the same target and configuration, and this alias is
/// that step's type, so the call needs no cast and no second translation.
pub const TranslateModule = *std.Build.Step.TranslateC;

/// The prefix `runtime/sync.c` is compiled with.
///
/// `runtime/library.zig` declares the same prefix in the symbol names it binds.
/// The two must agree, and a build where they do not fails to link, which is
/// the whole error report: there is no runtime path that could hide it.
///
/// The name is the module's own, so this SDK's five synchronization functions
/// cannot be confused with the same five from any other foundation SDK in the
/// same program. A build that needs a second, independent instance of this SDK
/// in one binary should change this value *and* the prefix in
/// `runtime/library.zig`, and then give the second instance its own copy of
/// both files. Nothing else in the package assumes one instance.
const sync_prefix = "proj_rt";

/// `extern` declarations that are the C library's, and that must therefore stay
/// direct.
///
/// **This list is empty, and that is a reading of the header rather than an
/// omission.** The translated unit is `zig/translate.h`, and it opens exactly
/// two upstream headers. `src/proj.h:121` includes `<stddef.h>` "For size_t",
/// and `src/proj.h:128` includes `proj_symbol_rename.h` only under
/// `PROJ_RENAME_SYMBOLS`, which neither delivery defines - so the closure is
/// `<stddef.h>` alone. `<stddef.h>` declares types and macros (`size_t`,
/// `ptrdiff_t`, `NULL`, `offsetof`, `max_align_t`) and **no function at all**,
/// so there is not a single C library name for a provider to be asked about and
/// not a single one that could be misrouted. This is the one header in this
/// package whose translated closure is empty, and it is empty for a reason the
/// header states.
///
/// The second header, `src/proj_constants.h`, is 520 `#define`s and nothing
/// else: no declaration, no function, no type. The translation step evaluates it
/// into Zig `pub const` declarations, which the generator re-exports; none of
/// them is an `extern`, so none of them can reach this list or `symbols`.
///
/// The list is spelled out as empty anyway, because a header that gains an
/// `#include` turns this into a build-file change with names in it rather than a
/// silent misroute of libc. PROJ's own compiled sources include `<math.h>`,
/// `<stdio.h>`, `<string.h>` and more (`src/4D_api.cpp:31-39` and its siblings),
/// but the library is a separate translation unit, and a declaration reaches the
/// dispatch only if the header this build translates declares it.
const libc_noise = "";

/// `extern` declarations the provider may legitimately not export.
///
/// **None, and nothing in this header belongs here.** All 292 `proj_*`
/// functions `src/proj.h` declares are unconditional at this pin: the header has
/// no `#if` around any entry point. The complete list of its conditionals is
/// the include guard (`:118-119`, `:2318`), the deprecated-API opt-out
/// (`:123-125`), the `PROJ_RENAME_SYMBOLS` include (`:127-129`), the C++
/// `extern "C"` opening (`:131-133`), the `PJ_DEFAULT_CTX` macro (`:399-403`),
/// and `PROJ_DEPRECATED` selecting between four spellings of the same attribute
/// (`:157-173`). Four declarations do go through `PROJ_DEPRECATED`
/// - `proj_list_units` (`:795`), `proj_list_angular_units` (`:797`),
/// `proj_errno_string` (`:775`) and `proj_rtodms` (`:811`) - and every branch of
/// that macro still declares the function; only the deprecation attribute
/// changes.
///
/// The distinction matters for the record. Marking an entry point optional would
/// not help if it went missing anyway: an `extern` left direct in this
/// configuration has no library to resolve it against, because the whole point of
/// the runtime route is that nothing is linked. It would become a link-time
/// undefined symbol instead of an honest refusal at load time. Every name stays
/// required, and `runtime/library.zig` holds the count and the whole list.
const provider_optional = "";

/// `extern` declarations this build does not require from a provider.
///
/// None. Every function `src/proj.h` declares is expected from a provider, and a
/// provider that does not export one of them is refused rather than half used. A
/// name here would be routed into a nullable table field instead: its absence
/// would not fail the load, and its wrapper would stop the program by name.
/// Only `libc_noise` above keeps a declaration direct, and that list is empty
/// too, so every routed name in this package comes from a provider.
///
/// The one case that looks like an exception is `PROJ_RENAME_SYMBOLS`, and it is
/// not one: a provider built with it exports `internal_proj_*`
/// (`src/proj_symbol_rename.h`, 291 `proj_*` names plus the 21 bundled
/// GeographicLib `geod_*` ones), so it exports *none* of the 292 names under the
/// names this build asks for and is refused at the first of them with
/// `MissingSymbol`. That is the correct outcome, not a gap; `runtime/library.zig`
/// states the boundary.
const provider_excluded = "";

/// The loader core, for a *linked* build to import.
///
/// A linked build has no dispatch, so the facade needs the core module itself
/// for the two public types `LoadSource` and `LoadError`: they are this SDK's
/// types and they must be the same types a caller names in either configuration.
/// It costs a linked build two declarations and no code, since nothing else in
/// that module is referenced until a configuration actually instantiates the
/// loader.
///
/// A runtime-loading build must *not* import this separately: `createModule`
/// makes the one core instance the dispatch uses, and the dispatch re-exports the
/// two types from it. Two instances would be two sets of types, and a consumer
/// would be naming one while `load` expects the other.
pub fn createCoreModule(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    return b.createModule(.{
        .root_source_file = b.path("runtime/loader.zig"),
        .target = target,
        .optimize = optimize,
        // The Unix backend calls `dlopen`, which is libc. Nothing in this module
        // is compiled into a linked build, so this costs nothing there.
        .link_libc = true,
    });
}

/// The runtime-loaded `c` module for one target.
///
/// `translate` is the translation step for that same target and configuration;
/// its output is read by the generator, so the dispatch describes the header
/// this build actually selected rather than another one.
pub fn createModule(
    b: *std.Build,
    translate: TranslateModule,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    const core = createCoreModule(b, target, optimize);

    const library = b.createModule(.{
        .root_source_file = b.path("runtime/library.zig"),
        .target = target,
        .optimize = optimize,
    });
    library.addImport("rt", core);

    return createDispatchModule(b, translate, target, optimize, core, library);
}

/// What one generator run writes: the dispatch, and the translation it reads.
const GeneratedSources = struct {
    native: std.Build.LazyPath,
    dispatch: std.Build.LazyPath,
};

fn createDispatchModule(
    b: *std.Build,
    translate: TranslateModule,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    core: *std.Build.Module,
    library: *std.Build.Module,
) *std.Build.Module {
    const sources = generateDispatch(b, translate, target);

    const dispatch = b.createModule(.{
        .root_source_file = sources.dispatch,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    dispatch.addImport("rt", core);
    dispatch.addImport("library", library);

    // The patched translation, under a name that says what it is. Every type
    // and constant in the dispatch is re-exported from here rather than
    // restated, so `c.PJ_COORD` in a facade and `c_native.PJ_COORD` in the
    // dispatch are one nominal type, and `c_routed` is what makes the members
    // nested inside those types the routed wrappers.
    const native = b.createModule(.{
        .root_source_file = sources.native,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    native.addImport("c_routed", dispatch);
    dispatch.addImport("c_native", native);
    dispatch.addCSourceFiles(.{
        .files = &.{"runtime/sync.c"},
        .flags = &.{b.fmt("-DRT_SYNC_PREFIX={s}", .{sync_prefix})},
        .language = .c,
    });
    return dispatch;
}

/// Runs the generator over the translation step's real output.
///
/// The generator is a host program built and run by this build, so the dispatch
/// is produced for the target being built from that target's own translation.
/// The name carries the target triple so two targets configured in one build
/// graph do not race for one executable.
fn generateDispatch(
    b: *std.Build,
    translate: TranslateModule,
    target: std.Build.ResolvedTarget,
) GeneratedSources {
    const generator = b.addExecutable(.{
        .name = b.fmt("proj-runtime-generate-{s}", .{
            target.result.zigTriple(b.allocator) catch @panic("unspellable target"),
        }),
        .root_module = b.createModule(.{
            .root_source_file = b.path("runtime/generate.zig"),
            .target = b.graph.host,
            .optimize = .Debug,
        }),
    });

    const run = b.addRunArtifact(generator);
    run.addArg("--library");
    run.addArg("proj");
    run.addArg("--translate");
    run.addFileArg(translate.getOutput());
    if (libc_noise.len != 0) {
        run.addArg("--noise");
        run.addArg(libc_noise);
    }
    if (provider_optional.len != 0) {
        run.addArg("--optional");
        run.addArg(provider_optional);
    }
    if (provider_excluded.len != 0) {
        run.addArg("--exclude");
        run.addArg(provider_excluded);
    }
    run.addArg("--native-output");
    const native_source = run.addOutputFileArg("native.zig");
    run.addArg("--output");
    const dispatch_source = run.addOutputFileArg("dispatch.zig");
    return .{ .native = native_source, .dispatch = dispatch_source };
}